package com.quizcraft.quiz_service.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.atomic.AtomicInteger;

@Service
public class GuestRateLimitService {

    private static final Logger log = LoggerFactory.getLogger(GuestRateLimitService.class);

    public static final int MAX_GUEST_QUESTIONS = 30;

    private final HttpClient httpClient = HttpClient.newBuilder()
            .connectTimeout(Duration.ofSeconds(3))
            .build();

    private final ObjectMapper objectMapper = new ObjectMapper();

    // Fallback in-memory map if Redis is not configured or fails
    private final ConcurrentHashMap<String, AtomicInteger> localMemoryCache = new ConcurrentHashMap<>();

    private String getRedisUrl() {
        String url = System.getProperty("REDIS_REST_URL");
        if (url == null || url.trim().isEmpty()) {
            url = System.getenv("REDIS_REST_URL");
        }
        return url != null ? url.trim() : null;
    }

    private String getRedisToken() {
        String token = System.getProperty("REDIS_REST_TOKEN");
        if (token == null || token.trim().isEmpty()) {
            token = System.getenv("REDIS_REST_TOKEN");
        }
        return token != null ? token.trim() : null;
    }

    private String sanitizeIp(String ip) {
        if (ip == null || ip.trim().isEmpty()) {
            return "unknown";
        }
        return ip.trim().replaceAll("[^a-zA-Z0-9_.:-]", "_");
    }

    /**
     * Get the total questions generated by this IP so far
     */
    public int getQuestionCount(String rawIp) {
        String ip = sanitizeIp(rawIp);
        String redisUrl = getRedisUrl();
        String redisToken = getRedisToken();

        if (redisUrl != null && redisToken != null) {
            try {
                String endpoint = redisUrl.replaceAll("/+$", "") + "/get/guest:ip:" + ip + ":questions";
                HttpRequest request = HttpRequest.newBuilder()
                        .uri(URI.create(endpoint))
                        .header("Authorization", "Bearer " + redisToken)
                        .timeout(Duration.ofSeconds(3))
                        .GET()
                        .build();

                HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
                if (response.statusCode() == 200) {
                    JsonNode node = objectMapper.readTree(response.body());
                    JsonNode resultNode = node.path("result");
                    if (!resultNode.isNull() && !resultNode.isMissingNode()) {
                        int count = resultNode.asInt(0);
                        localMemoryCache.computeIfAbsent(ip, k -> new AtomicInteger(0)).set(count);
                        return count;
                    }
                    return 0;
                }
            } catch (Exception e) {
                log.warn("Failed to read guest limit from Redis for IP {}: {}. Falling back to local cache.", ip, e.getMessage());
            }
        }

        return localMemoryCache.computeIfAbsent(ip, k -> new AtomicInteger(0)).get();
    }

    /**
     * Record questions generated by guest IP
     */
    public void recordQuestions(String rawIp, int questionCount) {
        if (questionCount <= 0) return;
        String ip = sanitizeIp(rawIp);

        // Update local memory cache first
        localMemoryCache.computeIfAbsent(ip, k -> new AtomicInteger(0)).addAndGet(questionCount);

        String redisUrl = getRedisUrl();
        String redisToken = getRedisToken();

        if (redisUrl != null && redisToken != null) {
            try {
                String endpoint = redisUrl.replaceAll("/+$", "") + "/incrby/guest:ip:" + ip + ":questions/" + questionCount;
                HttpRequest request = HttpRequest.newBuilder()
                        .uri(URI.create(endpoint))
                        .header("Authorization", "Bearer " + redisToken)
                        .timeout(Duration.ofSeconds(3))
                        .POST(HttpRequest.BodyPublishers.noBody())
                        .build();

                HttpResponse<String> response = httpClient.send(request, HttpResponse.BodyHandlers.ofString());
                if (response.statusCode() == 200) {
                    log.info("Incremented guest question count for IP {} by {} in Redis", ip, questionCount);
                } else {
                    log.warn("Upstash Redis incrby error: HTTP {}", response.statusCode());
                }
            } catch (Exception e) {
                log.warn("Failed to update guest limit in Redis for IP {}: {}", ip, e.getMessage());
            }
        }
    }

    /**
     * Calculate remaining questions for IP
     */
    public int getRemainingQuestions(String ip) {
        int current = getQuestionCount(ip);
        return Math.max(0, MAX_GUEST_QUESTIONS - current);
    }

    /**
     * Check if the guest IP is allowed to generate the requested count of questions
     */
    public boolean canGenerate(String ip, int requestedCount) {
        int current = getQuestionCount(ip);
        return (current + requestedCount) <= MAX_GUEST_QUESTIONS;
    }
}
